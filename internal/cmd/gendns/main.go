// Command gendns writes internal/server/dnsprovider_select.go, which restricts
// the binary to a single lego DNS provider when built with -tags single_dns_provider.
// Run it from the module root:
//
//	go run ./internal/cmd/gendns <provider>
//	go build -tags single_dns_provider -o acmespider cmd/main.go
//
// <provider> is a lego DNS provider code, e.g. ionos (see
// https://go-acme.github.io/lego/dns/).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"text/template"
)

const outFile = "internal/server/dnsprovider_select.go"

// aliases maps lego packages to the other names lego accepts for them, see
// Aliases in lego's providers/dns/*/*.toml.
var aliases = map[string][]string{
	"acmedns":    {"acme-dns"},
	"domeneshop": {"domainnameshop"},
	"edgedns":    {"fastdns"},
	"linode":     {"linodev4"},
	"rfc2136":    {"dnsupdate"},
	"webnames":   {"webnamesru"},
}

var validPkg = regexp.MustCompile(`^[a-z0-9]+$`)

var tmpl = template.Must(template.New("").Parse(`// Code generated by gendns. DO NOT EDIT.

//go:build single_dns_provider

package server

import (
	"fmt"

	"github.com/go-acme/lego/v4/challenge"
	"github.com/go-acme/lego/v4/providers/dns/{{.Pkg}}"
)

// newDNSProvider only knows {{.Pkg}}, the sole DNS provider compiled in.
func newDNSProvider(name string) (challenge.Provider, error) {
	switch name {
	case {{range $i, $n := .Names}}{{if $i}}, {{end}}{{printf "%q" $n}}{{end}}:
		return {{.Pkg}}.NewDNSProvider()
	}
	return nil, fmt.Errorf("unrecognized DNS provider: %s (binary built only for {{.Pkg}})", name)
}
`))

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: gendns <lego DNS provider code, e.g. ionos>")
	}
	if err := run(os.Args[1]); err != nil {
		log.Fatal(err)
	}
}

func run(name string) error {
	pkg, err := pkgOf(name)
	if err != nil {
		return err
	}
	src, err := render(pkg)
	if err != nil {
		return err
	}
	return os.WriteFile(outFile, src, 0o644)
}

// pkgOf returns the lego package of a provider name, e.g. "fastdns" -> "edgedns".
func pkgOf(name string) (string, error) {
	for pkg, names := range aliases {
		if slices.Contains(names, name) {
			return pkg, nil
		}
	}
	if !validPkg.MatchString(name) {
		return "", fmt.Errorf("invalid DNS provider name %q", name)
	}
	return name, nil
}

// render returns the source of a newDNSProvider accepting all lego names of pkg.
func render(pkg string) ([]byte, error) {
	var buf bytes.Buffer
	data := struct {
		Pkg   string
		Names []string
	}{pkg, append([]string{pkg}, aliases[pkg]...)}
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return format.Source(buf.Bytes())
}
